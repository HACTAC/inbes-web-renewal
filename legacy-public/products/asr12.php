            <p>パソコンでの再生の際、録画ファイルにパスワードロック(数字4桁)をかけることができます。<br>
              パスワードロック機能を使用した場合、パソコンからのデータ再生は専用アプリケーションからパスワードロックの解除が必要になります。</p>

